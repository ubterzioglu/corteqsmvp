-- profession_title dropdown'ını relocation_professions tablosundan dinamik üret; böylece
-- yeni meslek ekleme sadece yukarıdaki iki tabloya INSERT ile yeterli olur, options'ı elle
-- senkron tutmak gerekmez.
update public.relocation_tool_questions
set options = (
  select coalesce(jsonb_agg(jsonb_build_object('value', profession_key, 'label', label_tr) order by label_tr), '[]'::jsonb)
  from public.relocation_professions
  where is_active
)
where tool_key = 'profession_salary'
  and question_key = 'profession_title';
